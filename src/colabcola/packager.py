def _safe(path):
    # Reject links/junctions before resolving so copied trees cannot escape declared roots.
    path = Path(os.path.abspath(path))
    for part in (path, *path.parents):
        if part.is_symlink() or (hasattr(part, 'is_junction') and part.is_junction()):
            raise SpecError(f'links/junctions are not supported: {path}')
    if not path.is_file() and not path.is_dir():
        raise SpecError(f'input is not a regular file or directory: {path}')
    return path


def _excluded(relative, patterns):
    parts = Path(relative).parts
    return (any(p in _EXCLUDED_DIRS for p in parts)
        or any(p.startswith('.env.') for p in parts) or parts[-1] in _EXCLUDED_FILES
        or relative.endswith(('.pyc','.pyo','.pem','.key','.colajob','.run.json','.colaml'))
        or any(p.startswith('.colabcola-package-') for p in parts)
        or any(p.endswith(('.run','.files')) for p in parts)
        or any(fnmatch.fnmatchcase(relative, pat) or fnmatch.fnmatchcase(parts[-1], pat) for pat in patterns))


def _private_host_path(path):
    """Protect every local profile, including inactive and legacy account data."""
    path = Path(os.path.abspath(path))
    roots = (Path.home()/".colabcola", Path.home()/".config/colabcola", *private_config_homes())
    return any(path == root or root in path.parents
               for root in (Path(os.path.abspath(value)) for value in roots))


def _safe_input(path):
    path = _safe(path)
    if _private_host_path(path):
        raise SpecError("Colabcola account configuration cannot be packaged")
    return path


def _files(root, patterns):
    # Check paths only, never credential contents. Named and legacy profiles stay
    # private even when the whole home directory is explicitly selected.
    if _private_host_path(root):
        raise SpecError("Colabcola account configuration cannot be packaged")
    if root.is_file():
        yield root, root.name
        return
    for directory, dirs, files in os.walk(root, followlinks=False):
        current = Path(directory)
        dirs[:] = sorted(d for d in dirs if not _private_host_path(current / d)
                         and not _excluded((current / d).relative_to(root).as_posix(), patterns))
        for d in dirs:
            _safe(current / d)
        for name in sorted(files):
            file = current / name; relative = file.relative_to(root).as_posix()
            if not _private_host_path(file) and not _excluded(relative, patterns):
                yield _safe(file), relative


def _requirements(paths):
    from packaging.requirements import Requirement, InvalidRequirement
    normal, locked = [], []
    for path in paths:
        text = _safe_input(path).read_text(encoding='utf-8-sig').replace('\\\n', ' ')
        for number, raw in enumerate(text.splitlines(), 1):
            line = raw.split('#',1)[0].strip()
            if not line: continue
            if ' --hash=' in line:
                locked.append(line)
                continue
            try:
                req = Requirement(line)
            except InvalidRequirement:
                raise SpecError(f'{path}:{number}: expected a PyPI requirement; nested files, pip options and local installs are not supported') from None
            if req.url:
                raise SpecError(f'{path}:{number}: URL requirements are not supported; use index requirements')
            normal.append(str(req))
    return list(dict.fromkeys(normal)), list(dict.fromkeys(locked))


def package(args):
    if args.output is None: raise SpecError('output was not resolved')
    output = Path(os.path.abspath(args.output))
    if output.suffix != '.colajob': raise SpecError('--output must end in .colajob')
    assets = output.with_suffix('.files'); config_path = output.with_suffix('.run.json')
    if any(p.exists() for p in (output, assets, config_path)):
        raise SpecError('destination already exists; choose a new --output')
    if bool(args.drive_parent) != bool(args.token_command):
        raise SpecError('--drive-parent and --token-command must be supplied together')
    if args.runtime_version != 'latest' and args.provider_backend != 'rest':
        raise SpecError('Colab CLI adapter cannot select dated runtimes; beta REST requires separate allowlisted access')
    if not 1 <= args.max_runtimes <= 3 or not 60 <= args.max_seconds <= 86400:
        raise SpecError('execution bounds are 1-3 runtimes and 60-86400 seconds')
    if not 0 < args.timeout < args.max_seconds:
        raise SpecError('--timeout must be positive and below --max-seconds to leave time for recovery')
    if args.resume_arg and (not args.checkpoint or not args.resume_arg.startswith('--')):
        raise SpecError('--resume-arg requires --checkpoint and an option beginning with --')
    command = args.command[1:] if args.command[:1] == ['--'] else args.command
    if getattr(args, 'command_arrays', None):
        commands = args.command_arrays
    elif args.commands:
        if command: raise SpecError('use either --commands or a command, not both')
        commands = json.loads(_safe_input(args.commands).read_text(encoding='utf-8-sig'))
    else: commands = [command]
    if not isinstance(commands,list) or not commands or len(commands)>128:
        raise SpecError('commands must be a nonempty array of at most 128 argv arrays')
    normalized = []; console_commands = []
    for cmd in commands:
        if not isinstance(cmd,list) or not cmd or any(not isinstance(a,str) or '\0' in a for a in cmd):
            raise SpecError('each command must be a nonempty string argv array without NUL bytes')
        cmd = list(cmd)
        python_command = bool(re.fullmatch(r'python(?:3(?:\.\d+)?)?(?:\.exe)?', cmd[0]))
        if python_command: cmd.pop(0)
        if not cmd: raise SpecError('Python command needs a script or -m MODULE')
        console = not python_command and cmd[0] != '-m' and not cmd[0].endswith('.py')
        if console:
            if not re.fullmatch(r'[A-Za-z0-9_][A-Za-z0-9_.-]*', cmd[0]) or cmd[0] in ('bash','sh','cmd','powershell','pwsh'):
                raise SpecError('use a portable installed console command; shell programs are not supported')
        elif cmd[0] != '-m' and not cmd[0].endswith('.py'):
            raise SpecError('Python commands must run a .py script or -m MODULE')
        if cmd[0]=='-m' and (len(cmd)<2 or not re.fullmatch(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*',cmd[1])):
            raise SpecError('python -m needs a dotted module name')
        console_commands.append(console)
        normalized.append(cmd)
    if len(normalized)>1 and args.resume_arg:
        raise SpecError('resume-arg currently supports one command; sequences restart from their first command')
    project = _safe_input(args.project) if args.project else None
    if project and not project.is_dir(): raise SpecError('--project must be a directory')
    if not project and (len(normalized)>1 or normalized[0][0]=='-m'):
        raise SpecError('module and sequence packaging requires --project')
    files = {}
    def add(source,target,role):
        if _private_host_path(source):
            raise SpecError('Colabcola account configuration cannot be packaged')
        target = _portable_path(target, 'package target')
        if target.split('/')[0]=='_colabcola': raise SpecError('_colabcola is reserved for generated packaging files')
        normalized_target = target.casefold()
        if any(normalized_target == n.casefold() for n in files):
            raise SpecError(f'duplicate packaged target (case-insensitive): {target}')
        if any(normalized_target.startswith(n.casefold()+'/') or n.casefold().startswith(normalized_target+'/') for n in files):
            raise SpecError(f'file/directory target collision: {target}')
        files[target]=(source,role)
    if project:
        patterns = list(args.exclude)
        ignore = project/'.colabcolaignore'
        if ignore.is_file(): patterns += [s.strip() for s in ignore.read_text(encoding='utf-8').splitlines() if s.strip() and not s.lstrip().startswith('#')]
        for source,rel in _files(project,patterns):
            if source in (args.commands,): continue
            if getattr(args, 'include', []) and not any(fnmatch.fnmatchcase(rel, pat) for pat in args.include): continue
            add(source,rel,'source')
    for cmd, console in zip(normalized, console_commands):
        if console: continue
        if cmd[0]=='-m':
            module = cmd[1].replace('.','/')
            if module+'.py' not in files and module+'/__main__.py' not in files and not getattr(args, 'allow_installed_modules', False):
                raise SpecError(f'module {cmd[1]} is not included under --project')
        else:
            if project:
                path = Path(cmd[0]); path = path if path.is_absolute() else project/path
                source = _safe(path)
                try: rel = source.relative_to(project).as_posix()
                except ValueError: raise SpecError('script is outside --project') from None
                if rel not in files: raise SpecError(f'entrypoint excluded from project: {rel}')
            else:
                source = _safe(Path(cmd[0])); rel=source.name
                if not source.is_file(): raise SpecError('script must be a file')
                add(source,rel,'source')
            cmd[0]=rel
    for mapping in args.data:
        if '=' not in mapping: raise SpecError('--data requires SOURCE=TARGET (target is relative to job root)')
        source,target=mapping.split('=',1);source=_safe(Path(source));target=_portable_path(target,'data target')
        if source.is_dir():
            for file,rel in _files(source,[]):add(file,target+'/'+rel,'data')
        else:add(source,target,'data')
    wheels=[]
    for path in args.wheel:
        source=_safe(path)
        if not source.is_file() or source.suffix != '.whl':
            raise SpecError('--wheel requires a regular .whl file')
        target='wheels/'+source.name
        add(source,target,'wheel');wheels.append(target)
    remote_inputs=[]
    for path in args.remote_inputs:
        records=json.loads(_safe_input(path).read_text(encoding='utf-8-sig'))
        if not isinstance(records,list):
            raise SpecError('--remote-inputs must contain a JSON array')
        remote_inputs.extend(records)
    pip_requirements,locked=_requirements(args.requirements)
    pip_requirements=list(dict.fromkeys(pip_requirements+getattr(args,"extra_requirements",[])))
    env={'PYTHONUNBUFFERED':'1'}
    for item in args.env:
        if '=' not in item: raise SpecError('--env requires NAME=VALUE')
        key,value=item.split('=',1);env[key]=value
    name=args.name or re.sub('[^a-z0-9]+','-',output.stem.lower()).strip('-')
    # Execution policy is portable; account access is resolved from login at run time.
    config={'profile':'default','gpu':args.gpu,'max_attempts':args.max_runtimes,
            'max_seconds':args.max_seconds,'fault_after_checkpoint':False,
            'provider_backend':args.provider_backend,'high_mem':args.high_mem}
    argv=None
    if args.drive_parent:
        helper=_safe(args.token_command)
        argv=json.loads(helper.read_text(encoding='utf-8-sig'))
        if not isinstance(argv,list) or not argv or any(not isinstance(v,str) or not v for v in argv):
            raise SpecError('token-command must name a JSON array of helper arguments')
        # Copy argv only. No helper execution or credential access during packaging.
        config={'drive_parent':args.drive_parent,'token_command':assets.name+'/_colabcola/drive-helper.json',
            'gpu':args.gpu,'max_attempts':args.max_runtimes,'max_seconds':args.max_seconds,'fault_after_checkpoint':False, 'provider_backend':args.provider_backend, 'high_mem':args.high_mem}
    output.parent.mkdir(parents=True,exist_ok=True)
    temporary=Path(tempfile.mkdtemp(prefix='.colabcola-package-',dir=output.parent))
    published=False
    committed=False
    created=[]
    try:
        payload=[]
        for target,(source,role) in sorted(files.items()):
            dest=temporary/target;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,dest)
            payload.append({'role':role,'source':assets.name+'/'+target,'target':target})
        generated=temporary/'_colabcola';generated.mkdir()
        (generated/'launch.py').write_text(_LAUNCHER,encoding='utf-8',newline='\n')
        command_config={'commands':normalized,'resume_arg':args.resume_arg}
        if any(console_commands): command_config['console_commands']=console_commands
        (generated/'commands.json').write_text(json.dumps(command_config,sort_keys=True)+'\n',encoding='utf-8',newline='\n')
        for filename in ('launch.py','commands.json'):
            payload.append({'role':'source','source':assets.name+'/_colabcola/'+filename,'target':'_colabcola/'+filename})
        if argv is not None: (generated/'drive-helper.json').write_text(json.dumps(argv)+'\n',encoding='utf-8')
        job={'schema_version':1,'name':name,'payload':payload,
            'entrypoint':{'kind':'python_script','path':'_colabcola/launch.py','cwd':'.','argv':[]},
            'python':{'requires_python':args.requires_python,'runtime_requirements':args.runtime_requirement,'install_requirements':locked,'embedded_wheels':wheels},
            'runtime':{'provider':'google_colab','version':args.runtime_version},
            'resources':{'accelerator':'cpu' if args.gpu=='NONE' else 'gpu','gpu_count':0 if args.gpu=='NONE' else 1,'cuda_required':args.gpu!='NONE','minimum_gpu_memory_bytes':args.minimum_gpu_memory_bytes},
            'run':{'timeout_seconds':args.timeout,'seed':args.seed,'environment':env,'capture_stdout':True,'capture_stderr':True},
            'outputs':[{'pattern':pat,'required':bool(args.artifact),'maximum_bytes':args.artifact_max_bytes} for pat in (args.artifact or ['outputs/**'])],
            'limits':{'maximum_file_count':max(100,len(payload)+len(remote_inputs)+10)},
            'managed_recovery':{'checkpoint_pattern':args.checkpoint or 'outputs/_colabcola/disabled-*.json','log_patterns':args.log}}
        if args.artifact_group: job['managed_recovery']['artifact_groups']=args.artifact_group
        if remote_inputs: job['remote_inputs']=remote_inputs
        if args.isolated_python:
            from .python_profiles import PYTHON_312
            job['python']['isolation'] = dict(PYTHON_312)
        if pip_requirements:job['python']['pip_requirements']=pip_requirements
        # Validate and compile against the staged bytes before exposing the job.
        preview=json.loads(json.dumps(job))
        for item in preview['payload']:item['source']=str(temporary/item['target'])
        bundle=build_bundle(bind_job_arguments(JobSpec.from_mapping(preview)))
        os.rename(temporary,assets);published=True
        if config:
            with config_path.open('x',encoding='utf-8',newline='\n') as f:
                created.append(config_path);json.dump(config,f,indent=2);f.write('\n')
        with output.open('x',encoding='utf-8',newline='\n') as f:
            created.append(output);json.dump(job,f,indent=2);f.write('\n')
        committed=True
        return {'state':'packaged','job':str(output),'files_directory':str(assets),'job_id':bundle.job_id,
                'files':len(bundle.files),'input_bytes':bundle.raw_input_bytes,'commands':normalized,
                'execution_config':str(config_path) if config else None,
                'requested_gpu':args.gpu,'runtime_version':args.runtime_version,
                'provider_backend':args.provider_backend,'high_mem':args.high_mem,
                'dependency_policy':'remote index resolution; use hashed install requirements for locked dependencies' if pip_requirements else 'declared runtime constraints / hashed installs',
                'recovery':'checkpoint manifest plus resume argument' if args.resume_arg else 'restart commands from the beginning; no in-memory state capture'}
    finally:
        if not committed:
            for path in created:
                path.unlink()
            cleanup = assets if published else temporary
            if cleanup.resolve().parent != output.parent.resolve() or cleanup.is_symlink():
                raise SpecError('refusing cleanup outside the package destination')
            shutil.rmtree(cleanup)


def main(argv=None):
    arguments=list(sys.argv[1:] if argv is None else argv)
    cli_parser=parser()
    args=cli_parser.parse_args(arguments)
    try:
        with selected(args.profile):
            for source in (args.answers, args.commands):
                if source is not None:
                    _safe_input(source)
            guided = bool(args.answers or args.save_answers or args.interactive or args.non_interactive or args.command_strings or args.output is None)
            if guided:
                from .package_guide import guide, save_answers
                args, answers, save_path, questions = guide(args, arguments, cli_parser)
            result=package(args)
            if guided:
                result['questions_asked']=questions
                result['answers_file']=str(save_path) if save_path else None
                if save_path: save_answers(save_path, answers)
            print(json.dumps(result,indent=2))
            return 0
    except (SpecError,BundleError,LifecycleError,OSError,ValueError,EOFError,KeyboardInterrupt) as exc:
        print(f'colabcola package: {exc}',file=sys.stderr)
        return 2
