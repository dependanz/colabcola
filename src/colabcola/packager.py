# No imported workload code or dependency inference runs on the packaging host.
_EXCLUDED_DIRS = {'.git', '.hg', '.svn', '.venv', 'venv', '__pycache__', '.pytest_cache',
                  '.mypy_cache', '.ruff_cache', 'node_modules', '.aws', '.ssh', '.colabcola', 'outputs', 'build', 'dist'}
_EXCLUDED_FILES = {'.env', 'credentials.json', 'client_secrets.json', 'token.json', 'colab-oauth.json', 'drive-oauth.json', 'drive-client.json', 'publisher_oauth.json'}

